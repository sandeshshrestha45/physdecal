r"""
physdecal manifest
Writes EXPERIMENTS.md: every run that exists, what it was, and where its
evidence lives.

    physdecal manifest

Regenerate it after any new run. It is built by scanning out/, never by hand,
so it cannot drift from what is actually on disk -- which is the only property
that makes it usable as a provenance record when the paper is being written
months later.
"""

import argparse
import csv
import glob
import json
import os
import time

import numpy as np

from physdecal import config as N


def _ink_caveat():
    """
    Caveat 1, which changes meaning the moment a chart is scanned.

    Measuring the gamut does not retroactively optimise anything against it.
    A patch built before the scan was built against whatever printable.csv
    held at the time, so its printability number describes how printable that
    patch happens to be and NOT a gamut it was aimed at. Stating those two as
    one thing is the error this caveat exists to prevent.
    """
    if not N.INK_MEASURED:
        return ("1. **The ink set is a placeholder** (`INK_MEASURED = False`). "
                "No printability number should be reported until "
                "`printable.csv` is a scan of the actual printer.")
    try:
        when = time.strftime("%Y-%m-%d", time.localtime(
            os.path.getmtime(N.PRINTABLE_COLOURS_CSV)))
    except OSError:
        when = "an unrecorded date"
    return ("1. **The ink set is measured** (`INK_MEASURED = True`): "
            "`printable.csv` is a scan of the printer and paper used for "
            "the physical experiment, taken %s, and "
            "`printable_requested.csv` is the placeholder cube it replaced. "
            "ONLY patches optimised after that date were optimised against "
            "this gamut. For any earlier patch the printability number says "
            "how printable it happens to be, not a constraint it was "
            "optimised under, and must be labelled that way or left out."
            % when)

def stats(path):
    with open(path, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    att = [r for r in rows if r["attackable"] == "1"]
    suc = [r for r in att if r["success"] == "1"]
    return len(rows), len(att), (len(suc) / len(att) if att else None)


def results_for(tag):
    out = []
    for arm in ("seg", "det"):
        pre = "%s_%s__" % (arm, tag)
        for p in sorted(glob.glob(os.path.join(N.RESULT_DIR, "%s*.csv" % pre))):
            key = os.path.basename(p)[len(pre):-4]
            kind = "attack"
            for b in ("anchor__", "grey__", "random__"):
                if key.startswith(b):
                    kind, key = "control:" + b[:-2], key[len(b):]
            out.append((arm, key, kind, p))
    return out


def main():
    argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter).parse_args()
    lines = ["# Experiment manifest",
             "",
             "Generated by `physdecal manifest` from the contents of `out/`. "
             "Regenerate after any new run.",
             "",
             "Every ASR below is over the **attackable set only** — instances "
             "the victim segmented or detected correctly *without* the patch. "
             "An empty attackable set is reported as undefined, never as zero.",
             ""]

    tags = sorted(d for d in os.listdir(N.PATCH_DIR)
                  if os.path.isfile(os.path.join(N.PATCH_DIR, d, "run.json"))) \
        if os.path.isdir(N.PATCH_DIR) else []

    lines += ["## Runs", "",
              "| tag | task | white box | size | mode | realism | sc | steps | chain | dof |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    for t in tags:
        with open(os.path.join(N.PATCH_DIR, t, "run.json"), encoding="utf-8") as f:
            m = json.load(f)
        wb = m.get("seg_model") or m.get("det_model") or "-"
        size = ("roof-fit" if m.get("patch_size_mode") == "roof"
                else "%.2f m" % (m.get("patch_size_m") or 0))
        lines.append("| `%s` | %s | %s | %s | %s | %s | %s | %s | %s | %s |"
                     % (t, m.get("task"), wb, size,
                        m.get("patch_size_mode", "fixed"),
                        m.get("realism_level"), m.get("supercell", "-"),
                        m.get("steps"), "on" if m.get("print_chain") else "off",
                        m.get("degrees_of_freedom", "-")))

    lines += ["", "## Evidence per run", ""]
    for t in tags:
        res = results_for(t)
        if not res:
            continue
        lines += ["### `%s`" % t, "",
                  "Patch: `out/patches/%s/` — `patch.png`, `patch_large.png`, "
                  "`patch.pt`, `run.json`, `history.csv`" % t, ""]
        rm = {}
        with open(os.path.join(N.PATCH_DIR, t, "run.json"), encoding="utf-8") as f:
            rm = json.load(f).get("realism_metrics", {})
        if rm:
            lines.append("Realism: %s"
                         % ", ".join("%s=%s" % (k, round(v, 3)
                                                if isinstance(v, float) else v)
                                     for k, v in rm.items()))
            lines.append("")
        lines += ["| arm | victim | kind | n | n_att | ASR | rows |",
                  "|---|---|---|---|---|---|---|"]
        for arm, victim, kind, p in res:
            n, na, a = stats(p)
            lines.append("| %s | `%s` | %s | %d | %d | %s | `%s` |"
                         % (arm, victim, kind, n, na,
                            "undefined" if a is None else "%.3f" % a,
                            os.path.relpath(p, N.EXP_ROOT).replace("\\", "/")))
        figs = sorted(glob.glob(os.path.join(N.FIGURE_DIR, "*%s*" % t)))
        pngs = [os.path.basename(f) for f in figs if f.endswith(".png")]
        if pngs:
            lines += ["", "Figures: " + ", ".join("`%s`" % f for f in pngs)]
        lines.append("")

    # standing artefacts that are not tied to one run
    lines += ["## Standing artefacts", "",
              "| what | where |", "|---|---|",
              "| Finetuned heads (6 seg decoders, 3 detector heads, YOLO) | `weights/` |",
              "| Reference decal designs | `data/reference/anchor_*.png` |",
              "| Ink set (%s — see below) | `data/reference/printable.csv` |"
              % ("MEASURED" if N.INK_MEASURED else "PLACEHOLDER"),
              "| Print-ready sheets | `out/print/<tag>__<target>/` |",
              "| Physical sessions | `out/physical/<session>/` |",
              "| Run logs | `out/logs/` |",
              "| Index caches | `out/cache/` |",
              ""]

    lines += ["## Caveats that travel with these numbers", "",
              _ink_caveat(),
              "2. **Three holdout vehicles.** Every ASR is an average over "
              "instances of three vehicles; use `physdecal stats` for "
              "vehicle-level bootstrap intervals and leave-one-vehicle-out "
              "before quoting a number.",
              "3. **Controls are size-matched.** Each control is pasted at the "
              "size of the patch it controls for; `net = ASR - control` is "
              "what the optimisation is worth.",
              "4. **Panels show selected instances.** Each panel writes a "
              "`_caption.txt` stating its selection rule verbatim.",
              "5. **Lighting** must not be presented as illumination "
              "robustness until `check_time_of_day.py` is re-run and its "
              "verdict recorded.",
              ""]

    os.makedirs(N.EXP_ROOT, exist_ok=True)
    p = os.path.join(N.EXP_ROOT, "EXPERIMENTS.md")
    with open(p, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s" % p)
    print("  %d runs, %d result files, %d figures"
          % (len(tags), len(glob.glob(os.path.join(N.RESULT_DIR, "*.csv"))),
             len(glob.glob(os.path.join(N.FIGURE_DIR, "*.png")))))


if __name__ == "__main__":
    main()
